import {
  compact,
  type CompactionResult,
  type ExtensionAPI,
} from "@earendil-works/pi-coding-agent";
import {
  createSettings,
  isInstallTelemetryEnabled,
  loadConfig,
  parseModelReference,
} from "./config.js";

function warn(message: string, error?: unknown): void {
  if (error === undefined) {
    console.warn(`[pi-compaction-model] ${message}`);
  } else {
    console.warn(`[pi-compaction-model] ${message}`, error);
  }
}

/**
 * App-attribution headers that OpenRouter uses to identify pi as a
 * registered agentic harness. OpenRouter's free endpoints only accept
 * requests carrying this attribution; Pi adds the same headers to session
 * requests via its provider-attribution module, but the compact() path it
 * exports bypasses that pipeline, so they are added here for OpenRouter
 * models.
 */
const OPENROUTER_ATTRIBUTION_HEADERS = {
  "HTTP-Referer": "https://pi.dev",
  "X-OpenRouter-Title": "pi",
  "X-OpenRouter-Categories": "cli-agent",
} as const;

/**
 * Add OpenRouter app attribution to the compaction request headers,
 * mirroring pi-coding-agent's mergeProviderAttributionHeaders: the
 * attribution is only sent when install telemetry is enabled, and
 * caller-provided headers take precedence.
 */
export function withOpenRouterAttribution(
  model: { provider: string; baseUrl: string },
  telemetryEnabled: boolean,
  headers: Record<string, string> | undefined,
): Record<string, string> | undefined {
  if (!telemetryEnabled) return headers;
  const isOpenRouter =
    model.provider === "openrouter" || model.baseUrl.includes("openrouter.ai");
  if (!isOpenRouter) return headers;
  return { ...OPENROUTER_ATTRIBUTION_HEADERS, ...headers };
}
/**
 * Hook-provided compactions are marked as extension-generated by Pi. Native
 * preparation intentionally does not trust arbitrary extension details, so it
 * will not carry their file lists into a later compaction. Since this extension
 * returns Pi's own details shape, restore those lists before calling native
 * compact() again. Sets make this harmless for native previous entries too.
 */
function restorePreviousFileOperations(
  preparation: {
    fileOps: { read: Set<string>; edited: Set<string> };
  },
  branchEntries: Array<{ type: string; details?: unknown }>,
): void {
  const previous = [...branchEntries].reverse().find((entry) => entry.type === "compaction");
  if (!previous || typeof previous.details !== "object" || previous.details === null) return;

  const details = previous.details as {
    readFiles?: unknown;
    modifiedFiles?: unknown;
  };

  if (Array.isArray(details.readFiles)) {
    for (const path of details.readFiles) {
      if (typeof path === "string") preparation.fileOps.read.add(path);
    }
  }

  if (Array.isArray(details.modifiedFiles)) {
    for (const path of details.modifiedFiles) {
      if (typeof path === "string") preparation.fileOps.edited.add(path);
    }
  }
}

export default function compactionModel(pi: ExtensionAPI): void {
  pi.on("session_before_compact", async (event, ctx) => {
    const settings = createSettings(ctx);
    const config = loadConfig(ctx, settings);
    if (!config || !config.reasons.includes(event.reason)) return;

    const reference = parseModelReference(config.model);
    if (!reference) {
      warn(`Invalid model '${config.model}'; expected provider/model. Using Pi's active model.`);
      return;
    }

    const model = ctx.modelRegistry.find(reference.provider, reference.modelId);
    if (!model) {
      warn(`Model not found: ${config.model}. Using Pi's active model.`);
      return;
    }

    try {
      const auth = await ctx.modelRegistry.getApiKeyAndHeaders(model);
      if (!auth.ok) {
        warn(`Authentication failed for ${config.model}: ${auth.error}. Using Pi's active model.`);
        return;
      }

      const headers = withOpenRouterAttribution(
        model,
        isInstallTelemetryEnabled(settings),
        auth.headers,
      );

      restorePreviousFileOperations(event.preparation, event.branchEntries);

      const MAX_ATTEMPTS = 3;
      const RETRY_DELAY_MS = 3_000;

      let result: CompactionResult | undefined;
      for (let attempt = 1; attempt <= MAX_ATTEMPTS; attempt++) {
        if (event.signal.aborted) return;
        try {
          result = await compact(
            event.preparation,
            model,
            auth.apiKey,
            headers,
            event.customInstructions,
            event.signal,
            config.thinkingLevel,
            undefined,
            auth.env,
          );
          break;
        } catch (error) {
          if (event.signal.aborted || attempt === MAX_ATTEMPTS) {
            if (!event.signal.aborted) {
              warn(
                `Compaction with ${config.model} failed after ${MAX_ATTEMPTS} attempts; using Pi's active model.`,
                error,
              );
            }
            return;
          }
          await new Promise<void>((resolve) => {
            const timer = setTimeout(resolve, RETRY_DELAY_MS);
            event.signal.addEventListener(
              "abort",
              () => {
                clearTimeout(timer);
                resolve();
              },
              { once: true },
            );
          });
          if (event.signal.aborted) return;
        }
      }

      return { compaction: result };
    } catch (error) {
      if (!event.signal.aborted) {
        warn(`Compaction with ${config.model} failed; using Pi's active model.`, error);
      }
      return;
    }
  });
}

